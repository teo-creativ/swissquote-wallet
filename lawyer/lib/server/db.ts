// Minimal table access for the lawyer node, with two implementations: MemoryDb (tests, local dev without Supabase) and SupabaseDb
// (service role key, server only; RLS is on with no policy). Business rules live in the callers, never here.
// Rows use the SQL column names (snake_case). Binary columns (shares.keyshare_enc, shares.nonce) are plain hex in the callers.
import { randomUUID } from "node:crypto";
import { createClient, type SupabaseClient } from "@supabase/supabase-js";

export type Row = Record<string, any>;
type Scalar = string | number | boolean | null;
export type Cond = Scalar | { gt?: Scalar; gte?: Scalar; lt?: Scalar; lte?: Scalar; neq?: Scalar; in?: Scalar[] };
export type Where = Record<string, Cond>;
export type Opts = { order?: [string, "asc" | "desc"]; limit?: number };

export class DbError extends Error {
  constructor(public kind: "UNIQUE" | "STORAGE") {
    super(kind === "UNIQUE" ? "Duplicate key" : "Storage error");
  }
}

export interface Db {
  /** Throws DbError("UNIQUE") when a unique constraint is violated. Resolves the stored row. */
  insert(table: string, row: Row): Promise<Row>;
  select(table: string, where?: Where, opts?: Opts): Promise<Row[]>;
  /** Resolves the rows that were updated. An update that matches nothing resolves []: this is how "first caller wins" is built. */
  update(table: string, where: Where, patch: Row): Promise<Row[]>;
  delete(table: string, where: Where): Promise<number>;
}

const BYTEA: Record<string, string[]> = { shares: ["keyshare_enc", "nonce"], node_sessions: ["state_enc", "nonce"] };
const BYTEA_PREFIX = "\\x";
/** Tables whose primary key is generated by the database (uuid) or a sequence (bigserial). Memory mimics it. */
const UUID_ID = new Set(["lawyers", "lawyer_passkeys", "clients", "invitations", "webauthn_challenges", "approval_requests", "decisions", "exit_requests"]);
const SEQ_ID = new Set(["audit_log"]);
/** Unique constraints (column lists) of sql/001 and sql/002. */
const UNIQUE: Record<string, string[][]> = {
  lawyers: [["webauthn_user_id"]],
  lawyer_passkeys: [["credential_id"]],
  clients: [["sq_ref"], ["wallet_address"]],
  invitations: [["token_hash"]],
  policies: [["client_id"]],
  recipients: [["client_id", "address"]],
  policy_versions: [["client_id", "version"]],
  shares: [["client_id", "generation"]],
  recovery_cases: [["recovery_id"]],
  audit_log: [["entry_hash"]],
  seen_nonces: [["nonce"]],
  sanctioned_addresses: [["address"]],
};

function matches(row: Row, where: Where): boolean {
  return Object.entries(where).every(([col, cond]) => {
    const v = row[col] ?? null;
    if (cond === null || typeof cond !== "object") return v === cond;
    const cmp = (a: Scalar, b: Scalar) => (typeof a === "string" && typeof b === "string" && /^\d{4}-\d\d-\d\dT/.test(a) ? Date.parse(a) - Date.parse(b) : Number(a) - Number(b));
    if (cond.gt !== undefined && !(v !== null && cmp(v, cond.gt) > 0)) return false;
    if (cond.gte !== undefined && !(v !== null && cmp(v, cond.gte) >= 0)) return false;
    if (cond.lt !== undefined && !(v !== null && cmp(v, cond.lt) < 0)) return false;
    if (cond.lte !== undefined && !(v !== null && cmp(v, cond.lte) <= 0)) return false;
    if (cond.neq !== undefined && v === cond.neq) return false;
    if (cond.in !== undefined && !cond.in.includes(v)) return false;
    return true;
  });
}

function sorted(rows: Row[], opts?: Opts): Row[] {
  let out = [...rows];
  if (opts?.order) {
    const [col, dir] = opts.order;
    const num = (x: any) => (typeof x === "string" && /^\d{4}-\d\d-\d\dT/.test(x) ? Date.parse(x) : x);
    out.sort((a, b) => (num(a[col]) < num(b[col]) ? -1 : num(a[col]) > num(b[col]) ? 1 : 0) * (dir === "asc" ? 1 : -1));
  }
  if (opts?.limit !== undefined) out = out.slice(0, opts.limit);
  return out;
}

export class MemoryDb implements Db {
  private tables = new Map<string, Row[]>();
  private seq = 0;
  private rows(table: string): Row[] {
    if (!this.tables.has(table)) this.tables.set(table, []);
    return this.tables.get(table)!;
  }
  async insert(table: string, row: Row): Promise<Row> {
    const stored: Row = { ...row };
    if (UUID_ID.has(table) && stored.id === undefined) stored.id = randomUUID();
    if (SEQ_ID.has(table) && stored.id === undefined) stored.id = ++this.seq;
    for (const cols of UNIQUE[table] ?? []) {
      if (cols.some((c) => stored[c] === undefined || stored[c] === null)) continue;
      if (this.rows(table).some((r) => cols.every((c) => r[c] === stored[c]))) throw new DbError("UNIQUE");
    }
    this.rows(table).push(stored);
    return { ...stored };
  }
  async select(table: string, where: Where = {}, opts?: Opts): Promise<Row[]> {
    return sorted(this.rows(table).filter((r) => matches(r, where)), opts).map((r) => ({ ...r }));
  }
  async update(table: string, where: Where, patch: Row): Promise<Row[]> {
    const hit = this.rows(table).filter((r) => matches(r, where));
    for (const r of hit) Object.assign(r, patch);
    return hit.map((r) => ({ ...r }));
  }
  async delete(table: string, where: Where): Promise<number> {
    const keep = this.rows(table).filter((r) => !matches(r, where));
    const n = this.rows(table).length - keep.length;
    this.tables.set(table, keep);
    return n;
  }
}

export class SupabaseDb implements Db {
  private db: SupabaseClient;
  constructor(url: string, serviceRoleKey: string) {
    this.db = createClient(url, serviceRoleKey, { auth: { persistSession: false, autoRefreshToken: false } });
  }
  private out(table: string, row: Row): Row {
    const r = { ...row };
    for (const c of BYTEA[table] ?? []) if (typeof r[c] === "string" && r[c].startsWith(BYTEA_PREFIX)) r[c] = r[c].slice(BYTEA_PREFIX.length);
    return r;
  }
  private in(table: string, row: Row): Row {
    const r = { ...row };
    for (const c of BYTEA[table] ?? []) if (typeof r[c] === "string") r[c] = BYTEA_PREFIX + r[c];
    return r;
  }
  private filter(q: any, where: Where) {
    for (const [col, cond] of Object.entries(where)) {
      if (cond === null) q = q.is(col, null);
      else if (typeof cond !== "object") q = q.eq(col, cond);
      else {
        if (cond.gt !== undefined) q = q.gt(col, cond.gt);
        if (cond.gte !== undefined) q = q.gte(col, cond.gte);
        if (cond.lt !== undefined) q = q.lt(col, cond.lt);
        if (cond.lte !== undefined) q = q.lte(col, cond.lte);
        if (cond.neq !== undefined) q = q.neq(col, cond.neq);
        if (cond.in !== undefined) q = q.in(col, cond.in);
      }
    }
    return q;
  }
  private fail(error: { code?: string } | null) {
    if (!error) return;
    // Only the error class leaves this layer: no SQL, no value.
    throw new DbError(error.code === "23505" ? "UNIQUE" : "STORAGE");
  }
  async insert(table: string, row: Row): Promise<Row> {
    const { data, error } = await this.db.from(table).insert(this.in(table, row)).select().single();
    this.fail(error);
    return this.out(table, data as Row);
  }
  async select(table: string, where: Where = {}, opts?: Opts): Promise<Row[]> {
    let q: any = this.filter(this.db.from(table).select("*"), where);
    if (opts?.order) q = q.order(opts.order[0], { ascending: opts.order[1] === "asc" });
    if (opts?.limit !== undefined) q = q.limit(opts.limit);
    const { data, error } = await q;
    this.fail(error);
    return ((data as Row[]) ?? []).map((r) => this.out(table, r));
  }
  async update(table: string, where: Where, patch: Row): Promise<Row[]> {
    const { data, error } = await this.filter(this.db.from(table).update(this.in(table, patch)), where).select();
    this.fail(error);
    return ((data as Row[]) ?? []).map((r) => this.out(table, r));
  }
  async delete(table: string, where: Where): Promise<number> {
    const { data, error } = await this.filter(this.db.from(table).delete(), where).select();
    this.fail(error);
    return (data as Row[] | null)?.length ?? 0;
  }
}

const holder = globalThis as unknown as { __lawyerDb?: Db };
/** Supabase when SUPABASE_URL is set, otherwise an in-memory store (local dev: state is lost on restart). */
export function getDb(env: Record<string, string | undefined> = process.env): Db {
  if (!holder.__lawyerDb) {
    if (env.SUPABASE_URL) {
      if (!env.SUPABASE_SERVICE_ROLE_KEY) throw new Error("SUPABASE_SERVICE_ROLE_KEY is not set");
      holder.__lawyerDb = new SupabaseDb(env.SUPABASE_URL, env.SUPABASE_SERVICE_ROLE_KEY);
    } else {
      holder.__lawyerDb = new MemoryDb();
    }
  }
  return holder.__lawyerDb;
}
